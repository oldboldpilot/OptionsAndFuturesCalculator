#!/usr/bin/env bash
# Capture a database's CURRENT schema as a baseline migration.
#
# @author Olumuyiwa Oluwasanmi
#
#   db_capture_baseline.sh [--out FILE] [--force]
#
# The baseline must start from reality, not from the schema someone remembers.
# Run it against the hosted database (OFC_DATABASE_URL) to write
# backend/db/migrations/0001_baseline.sql, then `db_migrate.sh seal`, then
# `db_migrate.sh adopt 0001` on that same database (adopt re-proves it with the
# drift gate before it records anything). READ-ONLY against the source: pg_dump
# and catalog SELECTs only.
#
# What it writes, in order, so a fresh database can replay it:
#   1. a precondition that auth.users exists (GoTrue owns that schema; it is
#      never created here)
#   2. the project's ROLES (cluster-level, so absent from any dump) as
#      idempotent DO blocks: ofc_app and ofc_refresh unless OFC_MANAGED_ROLES says otherwise
#   3. extensions the public schema uses
#   4. pg_dump --schema-only of public: tables, constraints, indexes, functions,
#      triggers, row-level-security flags, POLICIES and GRANTS
#   5. the guard triggers migration 08 attaches to auth tables (the one OFC
#      object that lives in GoTrue's schema), the token-column defaults of
#      migration 09, and the database's EVENT
#      triggers, which pg_dump -n public leaves out
#   6. the rows of public.protected_relations (the armed state of migration 08)
#
# Not captured: owners, passwords, row data elsewhere, anything in auth.*, and
# the ledger. pg_dump 18's per-run \restrict key is stripped, or
# every capture would hash differently, and so are CREATE/COMMENT ON SCHEMA
# public, which exist in every database already.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/db_common.sh"

TARGET="${DB_TARGET:-url}"
OUT="$MIG_DIR/0001_baseline.sql"; FORCE=0
while [[ $# -gt 0 ]]; do case "$1" in
    --out) OUT="$2"; shift 2 ;; --force) FORCE=1; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;; esac; done

if [[ -e "$OUT" && $FORCE -ne 1 ]]; then
    echo "refusing to overwrite $OUT (a sealed migration is append-only). Use --force only before it is sealed." >&2; exit 1
fi
ROLES="${OFC_MANAGED_ROLES:-ofc_app ofc_refresh}"
rolelist="$(printf "'%s'," $ROLES)"; rolelist="${rolelist%,}"

ver="$(pg_scalar "$TARGET" 'show server_version')" || exit 1
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
{
    echo "-- 0001_baseline: the schema as it was captured, not as it was designed."
    echo "--"
    echo "-- Generated by scripts/db_capture_baseline.sh from a server reporting PostgreSQL $ver."
    echo "-- Generated: $(date -u +%Y-%m-%dT%H:%MZ). DO NOT HAND-EDIT: this file is sealed by checksum."
    echo "-- A live database already holds this schema: record it with 'db_migrate.sh adopt 0001'."
    echo "-- A fresh database replays it (it needs auth.users from GoTrue first)."
    echo
    echo "DO \$pre\$ BEGIN"
    echo "    IF to_regclass('auth.users') IS NULL THEN"
    echo "        RAISE EXCEPTION 'auth.users is absent: start GoTrue (or load backend/db/scratch_auth_stub.sql on a SCRATCH database) before migration 0001';"
    echo "    END IF;"
    echo "END \$pre\$;"
    echo
    echo "-- ROLES (cluster-level; never part of a database dump)"
    pg_exec "$TARGET" -At -v ON_ERROR_STOP=1 -c "
        SELECT format(E'DO \$r\$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = %L) THEN CREATE ROLE %I; END IF; END \$r\$;\nALTER ROLE %I %s %s %s %s %s %s %s CONNECTION LIMIT %s;',
               rolname, rolname, rolname,
               CASE WHEN rolsuper THEN 'SUPERUSER' ELSE 'NOSUPERUSER' END,
               CASE WHEN rolcreatedb THEN 'CREATEDB' ELSE 'NOCREATEDB' END,
               CASE WHEN rolcreaterole THEN 'CREATEROLE' ELSE 'NOCREATEROLE' END,
               CASE WHEN rolinherit THEN 'INHERIT' ELSE 'NOINHERIT' END,
               CASE WHEN rolcanlogin THEN 'LOGIN' ELSE 'NOLOGIN' END,
               CASE WHEN rolreplication THEN 'REPLICATION' ELSE 'NOREPLICATION' END,
               CASE WHEN rolbypassrls THEN 'BYPASSRLS' ELSE 'NOBYPASSRLS' END,
               rolconnlimit)
          FROM pg_roles WHERE rolname IN ($rolelist) ORDER BY rolname" || exit 1
    echo
    echo "-- EXTENSIONS"
    pg_exec "$TARGET" -At -v ON_ERROR_STOP=1 -c "
        SELECT format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname)
          FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
         WHERE e.extname <> 'plpgsql' ORDER BY 1" || exit 1
    echo
    echo "-- SCHEMA (public): pg_dump --schema-only, no owners"
    pg_dump_exec "$TARGET" --schema-only --no-owner --no-publications --no-subscriptions \
        -n public || exit 1
    echo
    echo "-- OFC guard triggers attached to GoTrue-owned tables (migration 08)"
    pg_exec "$TARGET" -At -v ON_ERROR_STOP=1 -c "
        SET search_path = pg_catalog;
        SELECT pg_get_triggerdef(t.oid) || ';' FROM pg_trigger t
          JOIN pg_proc p ON p.oid = t.tgfoid JOIN pg_namespace pn ON pn.oid = p.pronamespace
         WHERE NOT t.tgisinternal AND pn.nspname = 'public'
           AND t.tgrelid IN (SELECT c.oid FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'auth')
         ORDER BY t.tgname" || exit 1
    echo
    echo "-- GoTrue token-column defaults migration 09 sets (the only auth.users facet OFC owns)"
    pg_exec "$TARGET" -At -v ON_ERROR_STOP=1 -c "
        SET search_path = pg_catalog;
        SELECT format('ALTER TABLE auth.users ALTER COLUMN %I SET DEFAULT %s;', a.attname, pg_get_expr(d.adbin, d.adrelid))
          FROM pg_attrdef d JOIN pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
         WHERE d.adrelid = to_regclass('auth.users') AND a.attname IN ('confirmation_token','recovery_token',
               'email_change','email_change_token_new','email_change_token_current','phone_change',
               'phone_change_token','reauthentication_token') ORDER BY a.attname" || exit 1
    echo
    echo "-- EVENT TRIGGERS (database-level; pg_dump -n public does not emit them)"
    pg_exec "$TARGET" -At -v ON_ERROR_STOP=1 -c "
        SET search_path = pg_catalog;
        SELECT format('CREATE EVENT TRIGGER %I ON %s%s EXECUTE FUNCTION %s();', et.evtname, et.evtevent,
                      CASE WHEN et.evttags IS NULL THEN ''
                           ELSE ' WHEN TAG IN (' || (SELECT string_agg(quote_literal(t), ', ') FROM unnest(et.evttags) t) || ')' END,
                      et.evtfoid::regproc::text)
               || CASE et.evtenabled WHEN 'O' THEN '' WHEN 'D' THEN format(E'\\nALTER EVENT TRIGGER %I DISABLE;', et.evtname)
                       WHEN 'R' THEN format(E'\\nALTER EVENT TRIGGER %I ENABLE REPLICA;', et.evtname)
                       ELSE format(E'\\nALTER EVENT TRIGGER %I ENABLE ALWAYS;', et.evtname) END
          FROM pg_event_trigger et ORDER BY et.evtname" || exit 1
    echo
    if [[ "$(pg_scalar "$TARGET" "select to_regclass('public.protected_relations') is not null")" == t ]]; then
        echo "-- ARMED GUARD LIST (migration 08)"
        pg_dump_exec "$TARGET" --data-only --inserts --on-conflict-do-nothing --no-owner \
            -t public.protected_relations || exit 1
    fi
} | sed -E '/^\\(un)?restrict /d; /^CREATE SCHEMA public;$/d; /^COMMENT ON SCHEMA public IS /d' > "$tmp" || { echo "capture failed" >&2; exit 1; }

[[ -s "$tmp" ]] || { echo "capture produced nothing" >&2; exit 1; }
mv "$tmp" "$OUT"; trap - EXIT
echo "wrote $OUT ($(wc -l < "$OUT") lines, source PostgreSQL $ver)"
echo "next: scripts/db_migrate.sh seal"
