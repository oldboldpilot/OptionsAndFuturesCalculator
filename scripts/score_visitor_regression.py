"""Score the mortgage assistant against the VISITOR REGRESSION corpus.

@author Olumuyiwa Oluwasanmi

    score_visitor_regression.py --target local:50871            # a native gRPC engine
    score_visitor_regression.py --target prod                   # https://api.optionsandfuturescalculator.com
    score_visitor_regression.py --self-test                     # prove the judge detects each defect class

The corpus is backend/tests/data/visitor_regression.jsonl (generated by
scripts/build_visitor_regression.py). Its header documents the CONTRACT it encodes: the assistant
returns only what the visitor stated or what follows from it, asks only for an ESSENTIAL missing
input, never refuses with "left out X", and computes calculations worded as questions.

WHAT IT PRINTS. One PASS/FAIL line per row with the reason, then totals by expected outcome, by
operation/group and by FAILURE CLASS:

    spurious_field     a field the visitor never stated (the form-overwriting zero)
    missing_field      a stated or essential field the answer omitted
    wrong_value        the right field with the wrong number
    wrong_operation    the right outcome kind naming the wrong calculation
    wrong_outcome      params / question / refusal when another was required (sub-typed)
    wrong_question     asked, but about something else
    left_out_refusal   the "The assistant left out X" refusal, which the contract forbids

PRODUCTION. Uses the partner key, which is read from --key-file and NEVER printed, with the
mortgagefvcalculator.com origin, at no more than --max-rps requests a second (default 2). A 429 is
waited out using the "retry in Ns" the engine names and retried; it is never scored as a failure.

TWO-TURN ROWS. `--two-turn-protocol engine` (default) sends turn 2 the way the ENGINE's contract
defines it: utterance = the ORIGINAL request, prior_question = the question the service asked,
prior_clarification = the visitor's reply. `site` sends it the way mortgage-nest-egg sends it today:
utterance = the REPLY, prior_clarification = the QUESTION, and the original request is not sent at
all -- which the engine cannot answer, and which is why that flag exists: it measures the break.

`--dispatch` also runs each answered params through sensen.finance.Finance and records whether the
RPC ACCEPTS them. mortgage-nest-egg passes the assistant's params to Finance unchanged, so a
stated-only answer that the RPC refuses is a field the client must complete -- evidence, not opinion.
"""
