def run_row(t, row: dict, protocol: str, dispatch: bool) -> dict:
    res = {"id": row["id"], "group": row["group"], "kind": row["kind"], "utterance": row["utterance"]}
    if "turns" not in row:
        actual = t.parse(row["utterance"])
        passed, cls, why = judge(row["expect"], actual)
        res.update(actual=actual, passed=passed, failure_class=cls, reason=why)
    else:
        first = t.parse(row["utterance"])
        passed, cls, why = judge(row["turns"][0]["expect"], first)
        res.update(turn1=first)
        if not passed:
            res.update(actual=first, passed=False, failure_class=cls, reason="turn 1: " + why)
        else:
            reply = row["turns"][1]["reply"]
            question = first.get("question", "")
            if protocol == "engine":
                second = t.parse(row["utterance"], prior_clarification=reply, prior_question=question)
            else:  # site
                second = t.parse(reply, prior_clarification=question)
            passed, cls, why = judge(row["turns"][1]["expect"], second)
            res.update(actual=second, passed=passed, failure_class=cls, reason=("turn 2: " + why) if why else "")
    if dispatch and res["actual"]["kind"] == "params":
        ok, err = t.finance(res["actual"]["operation"], res["actual"]["params"])
        res["dispatch"] = {"ok": ok, "error": err}
    return res


def rejudge(rows: list, files: list, out_json, quiet_pass: bool) -> int:
    """Judge recorded answers again. A row with no recorded answer is reported MISSING, not passed."""
    recorded = {}
    for f in files:
        for line in f.read_text().splitlines():
            if line.strip():
                r = json.loads(line)
                recorded[r["id"]] = r
    results, missing = [], []
    for row in rows:
        rec = recorded.get(row["id"])
        if rec is None or "actual" not in rec:
            missing.append(row["id"])
            continue
        res = {"id": row["id"], "group": row["group"], "kind": row["kind"], "utterance": row["utterance"],
               "actual": rec["actual"]}
        if "turn1" in rec:
            res["turn1"] = rec["turn1"]
        if "dispatch" in rec:
            res["dispatch"] = rec["dispatch"]
        if "turns" in row:
            ok1, c1, w1 = judge(row["turns"][0]["expect"], rec.get("turn1", rec["actual"]))
            if not ok1:
                res.update(passed=False, failure_class=c1, reason="turn 1: " + w1)
            else:
                ok, c, w = judge(row["turns"][1]["expect"], rec["actual"])
                res.update(passed=ok, failure_class=c, reason=("turn 2: " + w) if w else "")
            res["expect_kinds"] = row["turns"][1]["expect"]
        else:
            ok, c, w = judge(row["expect"], rec["actual"])
            res.update(passed=ok, failure_class=c, reason=w)
            res["expect_kinds"] = row["expect"]
        results.append(res)
        if not res["passed"]:
            print(f"FAIL {res['id']:<10} {res['kind']:<7} [{res['failure_class']}] {res['reason']}\n"
                  f"       {res['utterance'][:150]}")
        elif not quiet_pass:
            print(f"PASS {res['id']:<10} {res['kind']:<7} {res['actual'].get('operation', res['actual']['kind'])}")
    if missing:
        print(f"\nNOT RECORDED ({len(missing)}): {' '.join(missing)}")
    summarise(results)
    if out_json:
        slim = [{k: v for k, v in r.items() if k != "expect_kinds"} for r in results]
        out_json.write_text("\n".join(json.dumps(r, separators=(",", ":")) for r in slim) + "\n")
    return 0 if results and all(r["passed"] for r in results) and not missing else 1


def summarise(results: list, out=sys.stdout):
    def pct(a, b):
        return f"{a}/{b}"
    total = len(results)
    ok = sum(r["passed"] for r in results)
    print(f"\nTOTAL {pct(ok, total)} passed", file=out)

    def table(title, keyf):
        d = collections.defaultdict(lambda: [0, 0])
        for r in results:
            k = keyf(r)
            d[k][1] += 1
            d[k][0] += r["passed"]
        print(f"\nBY {title}", file=out)
        for k in sorted(d):
            print(f"  {k:<44} {d[k][0]:>3}/{d[k][1]:<3}", file=out)

    def expected_kind(r):
        kinds = {a["outcome"] for a in (r.get("expect_kinds") or [])}
        return "/".join(sorted(kinds))
    table("EXPECTED OUTCOME", expected_kind)
    table("OPERATION / GROUP", lambda r: r["group"])
    table("ROW KIND", lambda r: r["kind"])
    fails = collections.Counter(r["failure_class"] for r in results if not r["passed"])
    print("\nFAILURE CLASSES", file=out)
    for k, v in fails.most_common():
        print(f"  {k:<28} {v}", file=out)
    disp = [r for r in results if "dispatch" in r]
    if disp:
        bad = [r for r in disp if not r["dispatch"]["ok"]]
        print(f"\nFINANCE DISPATCH of answered params: {len(disp) - len(bad)}/{len(disp)} accepted", file=out)
        by = collections.Counter((r["actual"]["operation"], r["dispatch"]["error"]) for r in bad)
        for (op, err), n in sorted(by.items()):
            print(f"  {op:<28} x{n:<3} {err}", file=out)


