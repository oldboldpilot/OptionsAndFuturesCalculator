def self_test() -> int:
    exp_pay = [{"outcome": "params", "operation": "ComputePayment",
                "params": {"present_value": "400000", "rate": "0.005416666666667", "periods": "360"},
                "optional": []}]
    good = {"kind": "params", "operation": "ComputePayment",
            "params": {"present_value": "400000", "rate": "0.005416666666666", "periods": "360"}}
    checks = []

    def check(name, got, want_pass, want_class=""):
        passed, cls, why = judge(*got)
        okay = (passed == want_pass) and (cls == want_class if not want_pass else True)
        checks.append(okay)
        print(f"  {'ok  ' if okay else 'FAIL'} {name}: passed={passed} class={cls!r} {why[:90]}")

    print("judge self-test")
    check("control: correct answer passes (15-place rate truncation tolerated)", (exp_pay, good), True)
    check("(i) a spurious field is detected",
          (exp_pay, {**good, "params": {**good["params"], "monthly_hoa": "0"}}), False, "spurious_field")
    check("(ii) a missing field is detected",
          (exp_pay, {**good, "params": {k: v for k, v in good["params"].items() if k != "periods"}}),
          False, "missing_field")
    check("(iii) a wrong operation is detected", (exp_pay, {**good, "operation": "ComputeRate"}),
          False, "wrong_operation")
    check("(iv) a wrong outcome kind is detected (asked instead of answered)",
          (exp_pay, {"kind": "clarification", "question": "Over how many years?"}), False, "wrong_outcome:asked")
    check("(iv) a wrong outcome kind is detected (answered instead of refused)",
          ([{"outcome": "refusal", "reasons": ["OUT_OF_SCOPE"]}], good), False, "wrong_outcome:answered")
    check("a wrong value is detected", (exp_pay, {**good, "params": {**good["params"], "periods": "180"}}),
          False, "wrong_value")
    check("an optional field may appear", ([{**exp_pay[0], "optional": ["future_value"]}],
          {**good, "params": {**good["params"], "future_value": "0"}}), True)
    check("an alternative may match", (exp_pay + [{"outcome": "clarification", "asks": ["periods"]}],
          {"kind": "clarification", "question": "Over how many years?"}), True)
    check("a question about the WRONG field is detected",
          ([{"outcome": "clarification", "asks": ["periods"]}],
           {"kind": "clarification", "question": "What's the interest rate?"}), False, "wrong_question")
    check("the forbidden 'left out' refusal is its own class", (exp_pay, {"kind": "refusal",
          "reason": "INVALID_PARAMETERS",
          "message": 'The assistant left out "property_price", which ComputeRentVsBuy needs.'}),
          False, "left_out_refusal")
    check("an array compares elementwise", ([{"outcome": "params", "operation": "ComputeIrr",
          "params": {"values": "[-100,30.5]"}, "optional": []}],
          {"kind": "params", "operation": "ComputeIrr", "params": {"values": "[-100.0,30.50]"}}), True)
    check("an operation name in a refusal is an internal-text leak even where a refusal is wanted",
          ([{"outcome": "refusal", "reasons": ["OUT_OF_SCOPE"]}],
           {"kind": "refusal", "reason": "OUT_OF_SCOPE", "message": "ComputeRentVsBuy cannot do that"}),
          False, "internal_text_leak")
    check("a quoted field name in a question is an internal-text leak",
          ([{"outcome": "clarification", "asks": []}],
           {"kind": "clarification", "question": 'What is the "property_price"?'}), False, "internal_text_leak")
    check("a snake_case field name in a refusal is an internal-text leak",
          ([{"outcome": "refusal", "reasons": []}],
           {"kind": "refusal", "reason": "OUT_OF_SCOPE", "message": "the annual_rate_x was unclear"}),
          False, "internal_text_leak")
    check("plain language passes the hygiene check",
          ([{"outcome": "refusal", "reasons": ["OUT_OF_SCOPE"]}],
           {"kind": "refusal", "reason": "OUT_OF_SCOPE",
            "message": "I don't give financial advice -- try 'what would a $420,000 loan at 6.25% cost per month'."}), True)
    check("a 429 retry hint is parsed", ([], {"kind": "refusal", "reason": "OUT_OF_SCOPE", "message": ""}),
          False, "wrong_outcome:refused")
    assert retry_after("quota exceeded ... retry in 15s") == 15 and retry_after("nothing") is None
    bad = checks.count(False)
    print(f"{len(checks) - bad}/{len(checks)} self-checks passed")
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", help="local:PORT | prod | https://host")
    ap.add_argument("--corpus", type=Path, default=DEFAULT_CORPUS)
    ap.add_argument("--key-file", type=Path, default=DEFAULT_KEY_FILE)
    ap.add_argument("--two-turn-protocol", choices=("engine", "site"), default="engine")
    ap.add_argument("--dispatch", action="store_true")
    ap.add_argument("--max-rps", type=float, default=2.0)
    ap.add_argument("--only", nargs="*", help="row ids or id prefixes")
    ap.add_argument("--json", type=Path, help="write per-row results here")
    ap.add_argument("--rejudge", type=Path, nargs="+",
                    help="re-score answers ALREADY recorded in these result files against the current corpus "
                         "instead of calling a service (several files are merged, later wins). Production's "
                         "partner budget is ~190 parses an hour shared with the live site, so a recorded run "
                         "is judged again rather than repeated.")
    ap.add_argument("--quiet-pass", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    if not a.target and not a.rejudge:
        ap.error("--target (or --rejudge) is required")
    rows = [json.loads(l) for l in a.corpus.read_text().splitlines() if l.strip()]
    if a.only:
        rows = [r for r in rows if any(r["id"].startswith(p) for p in a.only)]
    if not rows:
        print("REFUSED: no corpus rows selected; a run that measures nothing is not a pass", file=sys.stderr)
        return 2
    if a.rejudge:
        return rejudge(rows, a.rejudge, a.json, a.quiet_pass)
    if a.target.startswith("local:"):
        t = LocalTransport(int(a.target.split(":", 1)[1]))
    else:
        host = PROD_HOST if a.target == "prod" else a.target
        t = ProdTransport(host, read_key(a.key_file), a.max_rps)
    results = []
    for row in rows:
        res = run_row(t, row, a.two_turn_protocol, a.dispatch)
        res["expect_kinds"] = row["expect"] if "turns" not in row else row["turns"][1]["expect"]
        results.append(res)
        if res["passed"]:
            if not a.quiet_pass:
                print(f"PASS {res['id']:<10} {res['kind']:<7} {res['actual'].get('operation', res['actual']['kind'])}")
        else:
            print(f"FAIL {res['id']:<10} {res['kind']:<7} [{res['failure_class']}] {res['reason']}\n"
                  f"       {res['utterance'][:150]}")
    summarise(results)
    if a.json:
        slim = [{k: v for k, v in r.items() if k != "expect_kinds"} for r in results]
        a.json.write_text("\n".join(json.dumps(r, separators=(",", ":")) for r in slim) + "\n")
    return 0 if all(r["passed"] for r in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
