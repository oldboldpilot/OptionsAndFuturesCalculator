def as_decimal(x):
    try:
        return Decimal(str(x).strip())
    except (InvalidOperation, ValueError):
        return None


def values_equal(expected: str, got: str) -> bool:
    """Numeric comparison for numbers and arrays, exact for enums and booleans."""
    e, g = str(expected).strip(), str(got).strip()
    if e.startswith("[") and g.startswith("["):
        try:
            ea, ga = json.loads(e), json.loads(g)
        except json.JSONDecodeError:
            return e == g
        return len(ea) == len(ga) and all(values_equal(str(x), str(y)) for x, y in zip(ea, ga))
    de, dg = as_decimal(e), as_decimal(g)
    if de is not None and dg is not None:
        tol = max(Decimal("1e-9"), Decimal("1e-9") * abs(de))
        return abs(de - dg) <= tol
    return e == g


def judge_params(alt: dict, actual: dict):
    """-> (ok, failure_class, reason) for ONE params alternative against an answered response."""
    if actual["operation"] != alt["operation"]:
        return False, "wrong_operation", f"named {actual['operation']}, wanted {alt['operation']}"
    exp, got = alt["params"], actual["params"]
    allowed = set(exp) | set(alt.get("optional", []))
    spurious = sorted(set(got) - allowed)
    if spurious:
        return False, "spurious_field", "fields the visitor never stated: " + ", ".join(
            f"{k}={got[k]}" for k in spurious)
    missing = sorted(set(exp) - set(got))
    if missing:
        return False, "missing_field", "omitted: " + ", ".join(missing)
    wrong = [k for k in exp if not values_equal(exp[k], got[k])]
    if wrong:
        return False, "wrong_value", "; ".join(f"{k}: wanted {exp[k]}, got {got[k]}" for k in wrong)
    return True, "", ""


def question_matches(asks: list, question: str) -> bool:
    if not asks:
        return bool(question.strip())
    for f in asks:
        cls = ASK_FIELD_CLASS.get(f)
        pattern = ASK_WORDING.get(cls, r".")
        if re.search(pattern, question, re.IGNORECASE):
            return True
    return False


# Words a VISITOR must never be shown. The UI renders a refusal's message and a clarification's
# question verbatim, so an operation name, a snake_case field name or a quoted field name in
# either is a leak of the engine's internals (observed live 2026-10-06: "left out
# \"property_price\", which ComputeRentVsBuy needs").
INTERNAL_TEXT = re.compile(r'Compute[A-Z]|_[a-z]+_|"[a-z]+_[a-z_]+"')


def visitor_text(actual: dict) -> str:
    if actual["kind"] == "refusal":
        return actual.get("message", "")
    if actual["kind"] == "clarification":
        return actual.get("question", "")
    return ""


def judge(expect: list, actual: dict):
    """Judge an actual response against a list of acceptable alternatives.

    -> (passed, failure_class, reason). The reported failure is that of the alternative closest to
    what was answered: same outcome kind first, then the same operation.
    """
    kind = actual["kind"]
    # The contract forbids this refusal outright: an essential field is asked about, a
    # non-essential one is omitted, and neither is ever "left out". It fails even where a refusal
    # would otherwise be an acceptable outcome.
    if kind == "refusal" and "left out" in actual.get("message", ""):
        return False, "left_out_refusal", actual["message"]
    leak = INTERNAL_TEXT.search(visitor_text(actual))
    if leak:
        return False, "internal_text_leak", f"the visitor would be shown {leak.group(0)!r} in: {visitor_text(actual)[:140]}"
    candidates = []
    for alt in expect:
        if alt["outcome"] == kind:
            if kind == "params":
                ok, cls, why = judge_params(alt, actual)
            elif kind == "clarification":
                if question_matches(alt.get("asks", []), actual["question"]):
                    ok, cls, why = True, "", ""
                else:
                    ok, cls, why = False, "wrong_question", f"asked {actual['question']!r}, wanted a question about {alt.get('asks')}"
            else:  # refusal
                reasons = alt.get("reasons", [])
                if not reasons or actual["reason"] in reasons:
                    ok, cls, why = True, "", ""
                else:
                    ok, cls, why = False, "wrong_outcome", f"refused {actual['reason']}, wanted one of {reasons}"
            if ok:
                return True, "", ""
            candidates.append((0 if (kind != "params" or alt.get("operation") == actual.get("operation")) else 1, cls, why))
    if candidates:
        candidates.sort(key=lambda c: c[0])
        return False, candidates[0][1], candidates[0][2]
    wanted = sorted({a["outcome"] for a in expect})
    if kind == "refusal" and "left out" in actual.get("message", ""):
        return False, "left_out_refusal", actual["message"]
    sub = {"params": "answered", "clarification": "asked", "refusal": "refused"}[kind]
    detail = actual.get("message") or actual.get("question") or ""
    if kind == "params":
        detail = actual["operation"]
    return False, f"wrong_outcome:{sub}", f"{sub} ({detail[:140]}), wanted {'/'.join(wanted)}"


