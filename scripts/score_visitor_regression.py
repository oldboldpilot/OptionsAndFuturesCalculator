class RateLimited:
    def __init__(self, max_rps: float):
        self.interval = 1.0 / max_rps if max_rps > 0 else 0.0
        self.last = 0.0

    def wait(self):
        now = time.monotonic()
        if self.interval and now - self.last < self.interval:
            time.sleep(self.interval - (now - self.last))
        self.last = time.monotonic()


def read_key(path: Path) -> str:
    for line in path.read_text().splitlines():
        if re.match(r"^\s+key\s", line):
            return line.split(None, 1)[1].strip()
    raise SystemExit(f"no 'key' line in {path}")


def retry_after(text: str) -> int | None:
    m = re.search(r"retry in (\d+)\s*s", text)
    return int(m.group(1)) if m else None


class ProdTransport:
    def __init__(self, host: str, key: str, max_rps: float):
        self.host, self.key, self.limit = host.rstrip("/"), key, RateLimited(max_rps)

    def _post(self, path: str, body: dict):
        while True:
            self.limit.wait()
            req = urllib.request.Request(
                self.host + path, data=json.dumps(body).encode(),
                headers={"content-type": "application/json", "x-api-key": self.key, "origin": PROD_ORIGIN})
            try:
                with urllib.request.urlopen(req, timeout=60) as r:
                    return r.status, json.loads(r.read() or b"{}")
            except urllib.error.HTTPError as e:
                text = e.read().decode(errors="replace")
                if e.code == 429:
                    time.sleep((retry_after(text) or 5) + 1)
                    continue
                try:
                    return e.code, json.loads(text)
                except json.JSONDecodeError:
                    return e.code, {"message": text[:300]}

    def parse(self, utterance, prior_clarification="", prior_question=""):
        body = {"utterance": utterance}
        if prior_clarification:
            body["prior_clarification"] = prior_clarification
        if prior_question:
            body["prior_question"] = prior_question
        status, j = self._post(ASSISTANT_PATH, body)
        return normalise_json(j)

    def finance(self, operation, params):
        status, j = self._post(f"/sensen.finance.Finance/{operation}", finance_body(params))
        if status == 200 and "message" not in j:
            return True, ""
        return False, str(j.get("message", j))[:200]


def normalise_json(j: dict) -> dict:
    if "params" in j:
        p = j["params"]
        return {"kind": "params", "operation": p.get("operation", ""), "params": dict(p.get("params", {}))}
    if "clarification" in j:
        return {"kind": "clarification", "question": j["clarification"].get("question", "")}
    if "refusal" in j:
        r = j["refusal"]
        return {"kind": "refusal", "reason": r.get("reason", ""), "message": r.get("message", "")}
    return {"kind": "refusal", "reason": "TRANSPORT", "message": str(j)[:300]}


def finance_body(params: dict) -> dict:
    """The params map as a Finance request: an array arrives as a JSON-array STRING and a boolean as
    "true"/"false", exactly the coercion mortgage-nest-egg's coerceRequestForJson performs."""
    body = {}
    for k, v in params.items():
        if isinstance(v, str) and v.startswith("["):
            body[k] = json.loads(v)
        elif v in ("true", "false"):
            body[k] = (v == "true")
        else:
            body[k] = v
    return body


