def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "data_mortgage"))
    ap.add_argument("--n", type=int, default=12000)
    ap.add_argument("--seed", type=int, default=3407)
    ap.add_argument("--val-frac", type=float, default=0.05)
    args = ap.parse_args()

    rng = random.Random(args.seed)

    print(f"parsed {len(_PARSED['rpcs'])} RPCs from {PROTO_PATH}")
    print(f"in-scope operations (label space): {len(OPERATIONS)}")
    for name in sorted(OPERATIONS):
        print(f"    {name}  <- fields: {[f['name'] for f in OPERATIONS[name]['fields']]}")

    # Mix. Extraction generators are weighted roughly by how often each
    # operation family is the natural target of a plain-English mortgage/FV
    # question: amortization (the full schedule) and the basic TVM solvers
    # (payment/PV/FV/rate/periods) are the headline cases, mirroring how
    # build_dataset.py weights plain extraction at 0.50. Refinance and
    # rent-vs-buy get a full-size slice (not a token one) because CLAUDE.md
    # names both explicitly as the questions this domain gets asked
    # constantly -- unlike the smaller recast/payoff-timing/home-NPV/home-FV
    # slices, which are real and useful but less central. The rest exist so
    # the model does not treat every input as an extraction, exactly as in
    # build_dataset.py.
    #
    # make_refusal is 0.07 here, not the options assistant's 0.05 -- per
    # docs/superpowers/specs/2026-08-05-mortgagefv-assistant-pipeline.md,
    # deliberately above it, because a consumer-mortgage assistant
    # improvising lending/tax/legal advice is a worse liability than a
    # trading one improvising a strategy pick. Every extraction/
    # clarification/modification weight below is the ORIGINAL weight scaled
    # by ~0.897 to fund that increase (0.07 + 0.03 chitchat + 0.03
    # unknown-operation = 0.13, up from the original 0.11) while keeping the
    # relative shape of the extraction mix and --n unchanged -- see the
    # section-6 comment above make_refusal for why the two extra points of
    # weight were previously unreachable regardless of number.
    mix = [
        (0.152, make_amortization_extraction),
        (0.081, make_tvm_solver_extraction),
        (0.054, make_cashflow_extraction),
        (0.045, make_refinance_extraction),
        (0.045, make_rent_vs_buy_extraction),
        (0.036, make_heloc_extraction),
        (0.036, make_future_value_detailed_extraction),
        (0.036, make_rental_roi_extraction),
        (0.027, make_period_payment_extraction),
        (0.027, make_payback_extraction),
        (0.018, make_amortization_batch_extraction),
        (0.018, make_cumulative_extraction),
        (0.018, make_depreciation_extraction),
        (0.018, make_payoff_timing_extraction),
        (0.018, make_home_future_value_extraction),
        (0.0135, make_mortgage_recast_extraction),
        (0.0135, make_home_npv_extraction),
        (0.045, make_closing_costs_extraction),
        # Down payments carry the SAME weight as closing costs, and for the
        # same reason that operation was added: the failure was structural
        # rather than a weak model. "20% down" was out of distribution
        # entirely, and out-of-distribution here does not produce a refusal --
        # it produced a 20% interest rate that passed every gate.
        (0.045, make_down_payment_extraction),
        (0.126, make_clarification),
        (0.090, make_modification),
        (0.07, make_refusal),
        (0.03, make_chitchat),
        (0.03, make_unknown_operation),
    ]

    weights = [w for w, _ in mix]
    fns = [f for _, f in mix]

    rows, seen = [], set()
    counts = {fn.__name__: 0 for fn in fns}
    attempts = 0
    while len(rows) < args.n and attempts < args.n * 40:
        attempts += 1
        fn = rng.choices(fns, weights)[0]
        row = fn(rng)
        key = json.dumps(row, sort_keys=True)
        if key in seen:
            continue
        seen.add(key)
        rows.append(row)
        counts[fn.__name__] += 1

    rng.shuffle(rows)
    n_val = max(1, int(len(rows) * args.val_frac))
    val, train = rows[:n_val], rows[n_val:]

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, part in (("train", train), ("val", val)):
        p = out / f"{name}.jsonl"
        with p.open("w") as fh:
            for r in part:
                fh.write(json.dumps(r) + "\n")
        print(f"  {p}  {len(part)} rows")

    # PROVENANCE. The corpus is deterministic in (seed, n, val_frac) and the
    # generator source, and nothing else records which of those produced the
    # files on disk. That gap is not theoretical: the v4 corpus was built with
    # `--seed 0` (the invocation in this module's own docstring) while the
    # argparse DEFAULT is 3407, so a later rebuild "to change only the
    # closing-cost rows" silently reseeded all 11,400 and put held-out rows
    # into training. It was caught by diffing against a kept copy; without one
    # it would have been invisible and would have contaminated the holdout.
    meta = {
        "seed": args.seed,
        "n": args.n,
        "val_frac": args.val_frac,
        "rows": len(rows),
        "train_rows": len(train),
        "val_rows": len(val),
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "proto_sha256": hashlib.sha256(PROTO_PATH.read_bytes()).hexdigest(),
    }
    (out / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"  {out / 'meta.json'}  seed={args.seed} n={args.n} "
          f"generator={meta['generator_sha256'][:12]}")

    print(f"\n  requested {args.n}, produced {len(rows)} unique after dedup")
    print("  generator mix (measured):")
    for name, n in sorted(counts.items(), key=lambda kv: -kv[1]):
        print(f"    {name:38s} {n:6d}  {n/len(rows)*100:5.2f}%")

    # -- refusal training-mass check: what fraction of rows end WITHOUT a
    #    <params> block (the model declining rather than extracting), and --
    #    the number that actually matters, per the section-6 comment above
    #    make_refusal -- how many of those are DISTINCT (user, assistant)
    #    pairs rather than one templated sentence repeated. A high row count
    #    built from a handful of distinct pairs trains a parroted string,
    #    not a behaviour.
    no_params_rows = [r for r in rows if "<params>" not in r["conversations"][-1]["content"]]
    refusal_pairs = set()
    # A refusal-family row (make_refusal/make_chitchat/make_unknown_operation)
    # is exactly a three-turn [system, user, assistant] conversation with no
    # <params> in the assistant turn; clarification/modification rows always
    # end in a <params> block after 4+ turns, so this shape check alone is
    # enough to scope the count to the refusal family without needing to
    # carry generator identity through to the row itself.
    refusal_rows = []
    for r in no_params_rows:
        turns = r["conversations"]
        if len(turns) == 3:
            refusal_rows.append(r)
            refusal_pairs.add((turns[1]["content"], turns[2]["content"]))

    print(f"\n  rows with NO <params> block anywhere: {len(no_params_rows)} "
          f"({len(no_params_rows)/len(rows)*100:.2f}%)")
    print(f"  refusal-family (make_refusal/make_chitchat/make_unknown_operation) "
          f"rows: {len(refusal_rows)} ({len(refusal_rows)/len(rows)*100:.2f}%)")
    print(f"  distinct refusal-family (user, assistant) pairs: {len(refusal_pairs)}")

    # -- label-vs-proto validation: every operation id emitted in a <params>
    #    block must be an id this file actually derived from finance.proto.
    #    An id that is not is a training defect -- a label the backend has
    #    no RPC to serve.
    known = set(OPERATIONS)
    emitted, bad = set(), set()
    for r in rows:
        for turn in r["conversations"]:
            if turn["role"] == "assistant" and "<params>" in turn["content"]:
                op = json.loads(turn["content"][8:-9])["operation"]
                emitted.add(op)
                if op not in known:
                    bad.add(op)

    print(f"\n  operations covered: {len(emitted & known)}/{len(known)} "
          f"of the proto-derived label space")
    uncovered = known - emitted
    if uncovered:
        print(f"  WARNING uncovered operations: {sorted(uncovered)}")
    if bad:
        print(f"  FAIL: emitted operation ids not in finance.proto: {sorted(bad)}")
    else:
        print("  PASS: every emitted operation id exists in finance.proto")


if __name__ == "__main__":
    main()
