    fn = {"advice": _refusal_advice, "prediction": _refusal_prediction,
          "eligibility": _refusal_eligibility, "legal": _refusal_legal}[category]
    user, assistant = fn(rng)
    return convo(("system", SYSTEM), ("user", user), ("assistant", assistant))


