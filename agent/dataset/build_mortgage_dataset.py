#!/usr/bin/env python3
"""
Builds the supervised set for the mortgage/FV parameter agent.

Mirrors agent/dataset/build_dataset.py's shape and philosophy exactly: turn
what someone types into a chat box into the parameters `sensen.finance.Finance`
already accepts, or ask one question when that is not yet possible. It is NOT
a financial advisor. It does not opine on whether to refinance, whether now is
a good time to buy, or what someone's tax position should be -- the dataset
teaches it to decline that, for the same reason the options dataset does: a
0.6B model improvising financial advice on a page that computes real loan
numbers is the worst thing this could become.

THE LOAD-BEARING DESIGN PROPERTY, carried over unchanged from build_dataset.py:
the label space must come from the SAME place the backend validates against,
so the model and the backend cannot drift apart. build_dataset.py gets this
from strategies.json (also the source for strategy_catalogue.cppm). This file
has no such JSON catalogue to mirror -- `sensen.finance.Finance` has no
strategies.json equivalent -- so the label space is generated by PARSING
backend/proto/finance.proto directly: every RPC name and every field of its
request message is read out of the .proto text, not hand-typed here. See
`parse_finance_proto()` below. If a field is added to, say, AmortizationRequest,
this file's OPERATIONS dict picks it up automatically the next time it runs;
only the FIELD VALUE RANGES (what a plausible loan amount or rate looks like)
are hand-authored, exactly as EQUITIES/FUTURES/ALIASES are hand-authored in
build_dataset.py on top of a parsed catalogue.

SCOPE. `sensen.finance.Finance` serves five domains far outside a mortgage
assistant's job -- fixed income (bonds, T-bills), futures/margin/hedging,
options pricing, and portfolio statistics. Those are already a different
assistant's problem (or nobody's, yet). This generator's scope is fixed to
the RPCs the .proto file's own section banners
(`// -- Time value of money --`, `// -- Mortgages, HELOC --`, etc.) place
under: time value of money, mortgages/HELOC, cash-flow analysis,
depreciation, and real estate. That selection is made by parsing the section
banners too (see IN_SCOPE_SECTIONS), not by hand-listing 20 RPC names --
widening a banner's section in the .proto widens this dataset's scope
automatically. The one hand-curated exclusion is EXCLUDE_RPCS: two TVM
utilities (ConvertInterestRate, ComputeFisherRate) that fall under the
in-scope "Time value of money" banner but are rate-theory conversions
("nominal to effective", "real to nominal") nobody phrases as a mortgage chat
message -- excluded by explicit name, the same way build_dataset.py excludes
RTY/YM/NG/SI/ZN from FUTURES by explicit name rather than by some inferred
rule. This yields exactly 20 in-scope RPCs, matching the 20-of-36 the task's
own prior analysis found.

Six further sensen capabilities -- refinance break-even metrics, home NPV,
home FV, recast, payoff timing, rent-vs-buy -- were NOT in finance.proto when
this file was started, and the brief for this file said to design around
that with a speculative, hand-defined, off-by-default registry. Mid-session,
the proto GAINED real RPCs for exactly those six (ComputeRefinance,
ComputePayoffTiming, ComputeMortgageRecast, ComputeHomeFutureValue,
ComputeRentVsBuy, ComputeHomeNpv), all under the already-in-scope
"Mortgages, HELOC" and "Real estate" banners -- so `build_operations()`
picked them up automatically, with zero changes to IN_SCOPE_SECTIONS, in the
exact way the module docstring above promises ("widening a banner's section
in the .proto widens this dataset's scope automatically"). That is the
intended payoff of parsing rather than hand-listing, observed in practice
rather than asserted: this file now has real generators for all 26 in-scope
operations, and the speculative placeholder + its --include-future-ops flag
this paragraph used to describe have been deleted as no longer needed. If
finance.proto ever again gains a mortgage/real-estate RPC ahead of this file
having a generator for it, main()'s closing validation step reports it by
name as an uncovered operation -- it does not fail silently.

Output is ShareGPT-shaped JSONL, identical in shape to build_dataset.py's:
    {"conversations": [{"role": "...", "content": "..."}, ...]}

    python3 build_mortgage_dataset.py --out data_mortgage/ --n 12000 --seed 0
"""
