# Closing costs: the itemised cash-to-close estimate. Sixteen fields, every one
# of which must be STATED in the utterance -- the verifier grounds each emitted
# number against the request, so a field the phrasing leaves out is a refusal
# rather than a guess. That is why these utterances read as long as they do.
#
# Percentages are decimal fractions and their BASES DIFFER: origination and
# discount points are shares of the LOAN, title and transfer tax are shares of
# the PRICE. finance.proto says so on the fields themselves.
def make_closing_costs_extraction(rng: random.Random) -> dict:
    """Closing costs. Sixteen fields, and the phrasing carries the whole risk.

    Two shapes, deliberately mixed. The FULL shape names every figure. The
    SPARSE shape omits the costs that are zero and says nothing about prepaid
    interest -- which is how a real buyer writes, and which the earlier
    version of this generator never produced: it stated "$0 in seller/lender
    credits" and "0% discount points" in every row, so the model only ever saw
    a world where absent costs are announced.

    The sparse shape is only SAFE because mortgage_verification.cppm carries
    convention values for exactly these fields (zero for each omittable cost,
    15 for an unnamed prepaid-interest day count). A field omitted from the
    utterance and NOT in that list is an ungrounded value and gets refused, so
    the two files have to agree about which costs may go unsaid.
    """
    op = "ComputeClosingCosts"
    home_price = round_money(rng.randint(150_000, 1_200_000), nearest=5000)
    down_payment_percent = round(rng.choice(range(3, 26)) / 100.0, 4)
    annual_rate = round(rng.choice(range(450, 851, 25)) / 10000.0, 4)
    origination_fee_percent = 0.0 if rng.random() < 0.25 else round(rng.choice(range(25, 151, 25)) / 10000.0, 4)
    discount_points_percent = 0.0 if rng.random() < 0.35 else round(rng.choice(range(25, 201, 25)) / 10000.0, 4)
    other_lender_fees = 0.0 if rng.random() < 0.12 else float(round_money(rng.randint(700, 2500), nearest=50))
    title_settlement_percent = round(rng.choice(range(30, 81, 5)) / 10000.0, 4)
    appraisal_fee = 0.0 if rng.random() < 0.12 else float(round_money(rng.randint(450, 900), nearest=25))
    inspection_fee = 0.0 if rng.random() < 0.25 else float(round_money(rng.randint(300, 700), nearest=25))
    recording_fees = 0.0 if rng.random() < 0.12 else float(round_money(rng.randint(100, 400), nearest=10))
    transfer_tax_percent = 0.0 if rng.random() < 0.3 else round(rng.choice(range(50, 201, 25)) / 10000.0, 4)
    homeowners_insurance_annual = float(round_money(rng.randint(900, 4000), nearest=50))
    property_tax_annual = float(round_money(rng.randint(2000, 18000), nearest=100))
    tax_escrow_months = rng.randint(2, 6)
    seller_lender_credits = 0.0 if rng.random() < 0.45 else float(round_money(rng.randint(1000, 10000), nearest=500))
    sparse = rng.random() < 0.45
    # PREPAID INTEREST IS ALWAYS STATED, in every shape. Two ways of not
    # stating it have now been measured on held-out rows and both fail, for
    # the same reason:
    #
    #   * label it 15 (the convention) on an utterance that never mentions it
    #     -- the model emitted numbers scraped from elsewhere in the request
    #     (180, 30, 36, 150, 250). 21 of 26 closing-cost failures were this
    #     field alone.
    #   * OMIT the key, which is what finance.proto's explicit presence is for
    #     -- the model never once omitted it. 25 of 25 held-out rows whose gold
    #     omitted the field got a value anyway, 17 of them a literal 0, which
    #     is NOT the same computation: absent means `value_or(15)`, an explicit
    #     0 means a closing on the last day of a month owing nothing.
    #
    # 48% of training rows omitted it and inference omitted it 0% of the time.
    # The model treats a sixteen-field answer as a fixed schema and fills every
    # slot, so the only slot it can fill correctly is one the utterance
    # actually grounds. The sparse shape still omits ZERO COSTS, which is what
    # it exists for and which the model does handle; it just no longer omits
    # the one field that has no anchor.
    # The DRAW PATTERN is deliberately the original one -- the sparse branch
    # consumes no rng call and yields the convention value -- because every
    # generator here shares one Random and changing how many draws this
    # function makes reshuffles all 12,000 rows, moving held-out rows into
    # training. That is not hypothetical: it happened once in this session and
    # was caught only by diffing against a kept copy. A change meant to affect
    # one operation must consume the same randomness as what it replaces.
    prepaid_interest_days = 15 if sparse else (15 if rng.random() < 0.5 else rng.randint(10, 30))

    def money(v):
        return phrase_money(v)

    # Each clause is (text, is_present). In the sparse shape a zero cost simply
    # does not appear; in the full shape it is stated as zero.
    lender = []
    if origination_fee_percent or not sparse:
        lender.append(f"a {phrase_pct(origination_fee_percent)} origination fee")
    if discount_points_percent or not sparse:
        lender.append(f"{phrase_pct(discount_points_percent)} in discount points")
    if other_lender_fees or not sparse:
        lender.append(f"{money(other_lender_fees)} in other lender fees")

    third = [f"{phrase_pct(title_settlement_percent)} for title and settlement"]
    if appraisal_fee or not sparse:
        third.append(f"a {money(appraisal_fee)} appraisal")
    if inspection_fee or not sparse:
        third.append(f"a {money(inspection_fee)} inspection")

    govt = []
    if recording_fees or not sparse:
        govt.append(f"{money(recording_fees)} in recording fees")
    if transfer_tax_percent or not sparse:
        govt.append(f"a {phrase_pct(transfer_tax_percent)} transfer tax")

    prepaid = [f"homeowners insurance at {money(homeowners_insurance_annual)} a year",
               f"property tax at {money(property_tax_annual)} a year",
               f"{tax_escrow_months} months of tax escrow"]
    prepaid.append(f"{prepaid_interest_days} days of prepaid interest")
    if seller_lender_credits or not sparse:
        prepaid.append(f"{money(seller_lender_credits)} in seller or lender credits")

    def join(items):
        if not items:
            return ""
        if len(items) == 1:
            return items[0]
        return ", ".join(items[:-1]) + " and " + items[-1]

    head = rng.choice([
        f"What are my closing costs on a {money(home_price)} house with "
        f"{phrase_pct(down_payment_percent)} down at {phrase_pct(annual_rate)}?",
        f"I'm buying at {money(home_price)}, putting {phrase_pct(down_payment_percent)} down, "
        f"rate {phrase_pct(annual_rate)}. How much cash do I need to close?",
        f"Estimate cash to close: {money(home_price)} purchase, "
        f"{phrase_pct(down_payment_percent)} down payment, {phrase_pct(annual_rate)} interest rate.",
        f"Work out the closing costs on a {money(home_price)} purchase -- "
        f"{phrase_pct(down_payment_percent)} down, borrowing at {phrase_pct(annual_rate)}.",
    ])

    parts = [head]
    if lender:
        parts.append(f"Lender charges are {join(lender)}.")
    parts.append(f"Third-party costs are {join(third)}.")
    if govt:
        parts.append(f"Government fees are {join(govt)}.")
    parts.append(f"For prepaids and escrow: {join(prepaid)}.")
    user = " ".join(parts)

    # rate_str DEFAULTS to six places and every percent here is generated with
    # round(..., 4), so the default appended two zeros carrying no information
    # -- measured, 3270 of 3270 six-place labels ended in "00". The model
    # emitted the four-place majority convention it sees everywhere else, so
    # rows that were NUMERICALLY exact failed string equality: v4 scored 0/42
    # exact and 16/42 numerically on held-out closing costs, entirely from
    # this. Four places is not a house style imposed here -- it is the
    # precision the values actually have.
    #
    # Do NOT "normalise" the other six-place operations to match. Their rates
    # are PER-PERIOD (ComputePayment's 0.005625 is 6.75%/12) and genuinely
    # need six; truncating those to 0.0056 prices a different loan.
    obj = {
        "home_price": money_str(home_price),
        "down_payment_percent": rate_str(down_payment_percent, 4),
        "annual_rate": rate_str(annual_rate, 4),
        "origination_fee_percent": rate_str(origination_fee_percent, 4),
        "discount_points_percent": rate_str(discount_points_percent, 4),
        "other_lender_fees": money_str(other_lender_fees),
        "title_settlement_percent": rate_str(title_settlement_percent, 4),
        "appraisal_fee": money_str(appraisal_fee),
        "inspection_fee": money_str(inspection_fee),
        "recording_fees": money_str(recording_fees),
        "transfer_tax_percent": rate_str(transfer_tax_percent, 4),
        "homeowners_insurance_annual": money_str(homeowners_insurance_annual),
        "property_tax_annual": money_str(property_tax_annual),
        "tax_escrow_months": tax_escrow_months,
        "seller_lender_credits": money_str(seller_lender_credits),
        "prepaid_interest_days": prepaid_interest_days,
    }
    return convo(("system", SYSTEM), ("user", user), ("assistant", params_block(op, obj)))


# ============================================================================
# 3b. DOWN PAYMENTS -- a price and a deposit, where the LOAN is stated by
#     neither one.
#
#     Added 2026-08-29 after a measured production failure. On
#     "amortization schedule for a 500000 home with 20% down at 6.5% for 30
#     years" the deployed model returned `annual_rate = 0.2000` -- it read the
#     DOWN PAYMENT as the interest rate and dropped the stated 6.5% -- and the
#     grounding gate returned Proven, because 20 -> 0.20 is an ordinary
#     candidate for a rate slot. A real field, a parseable value, every bound
#     satisfied, and a 20% mortgage priced. On other phrasings of the same
#     request it emitted the FULL PRICE as the loan.
#
#     Neither is a decode fault. The corpus contained no utterance in which a
#     price and a deposit appear together, so "20% down" was out of
#     distribution and the nearest thing the model had seen was a rate.
#
#     THE LABEL IS DERIVABLE, which is the rule every generator in this file
#     obeys and the rule whose violation cost three retrains (see
#     phrase_money's docstring). `loan = price - down` does not appear in the
#     utterance as a literal, and it is admissible ONLY because
#     mortgage_verification.cppm gained map M9 the same day. Do not add rows of
#     this shape to a tree whose verifier predates that map: the model would be
#     trained to emit a figure the serving path then refuses, which is the
#     "squeezed from both sides" failure this corpus has already produced once.
#
#     Both spellings are generated, percent and money, because a model that
#     learned only one would be a trap rather than a fix -- and M9 admits both.
# ============================================================================


DOWN_PAYMENT_PERCENTS = [0.03, 0.05, 0.10, 0.15, 0.20, 0.25, 0.30]


def make_down_payment_extraction(rng: random.Random) -> dict:
    # Whole thousands, so `price - down` is exact at two places for every
    # percent in the table above and `phrase_money` renders it without cents.
    price = round_money(rng.triangular(180_000, 2_000_000, 480_000), 1_000)
    annual_rate = round(rng.uniform(0.045, 0.085), 4)
    term = rng.choices(MORTGAGE_TERM_MONTHS, MORTGAGE_TERM_WEIGHTS)[0]

    # Both phrase tables below are NOUN phrases, because every template reads
    # "with <phrase>". A "putting ... down" variant was generated first and
    # produced "with putting 20% down", which is not English -- and a corpus of
    # ungrammatical utterances teaches the model that grammar carries no
    # information.
    as_percent = rng.random() < 0.55
    if as_percent:
        pct = rng.choice(DOWN_PAYMENT_PERCENTS)
        down = round_money(price * pct, 1)
        down_phrase = rng.choice([
            f"{phrase_pct(pct)} down",
            f"{phrase_pct(pct)} down payment",
            f"a {phrase_pct(pct)} deposit",
        ])
    else:
        down = round_money(price * rng.uniform(0.05, 0.35), 1_000)
        down_phrase = rng.choice([
            f"{phrase_money(down)} down",
            f"a {phrase_money(down)} down payment",
            f"a {phrase_money(down)} deposit",
        ])
    loan = price - down

    # Guard rather than assert: a generator that silently emits an underivable
    # label is the exact defect this section exists to fix.
    if loan < 40_000 or down <= 0:
        return make_down_payment_extraction(rng)

    if rng.random() < 0.5:
        op = "ComputePayment"
        obj = {"rate": rate_str(annual_rate / 12), "periods": term,
               "present_value": money_str(loan), "future_value": money_str(0),
               "timing": "END_OF_PERIOD"}
        user = rng.choice([
            f"What's the monthly payment on a {phrase_money(price)} home with "
            f"{down_phrase} at {phrase_pct(annual_rate)} over {phrase_years(term)}?",
            f"I'm buying a {phrase_money(price)} house with {down_phrase}. "
            f"{phrase_pct(annual_rate)}, {phrase_years(term)} fixed -- what's the payment?",
            f"{phrase_money(price)} purchase, {down_phrase}, {phrase_pct(annual_rate)}, "
            f"{phrase_years(term)}. Monthly payment?",
        ])
    else:
        op = "ComputeAmortization"
        obj = {"loan_amount": money_str(loan), "annual_rate": rate_str(annual_rate, 4),
               "term_months": term, "monthly_overpayment": money_str(0),
               "pmi_annual_rate": rate_str(0, 4),
               # The home VALUE is the price, not the loan -- PMI drops off
               # against it. This is the one field where the gross figure is
               # correct, and getting it wrong is invisible without PMI.
               "original_home_value": money_str(price)}
        user = rng.choice([
            f"Amortization schedule for a {phrase_money(price)} home with {down_phrase} "
            f"at {phrase_pct(annual_rate)} for {phrase_years(term)}.",
            f"Amortize the loan on a {phrase_money(price)} property, {down_phrase}, "
            f"{phrase_pct(annual_rate)}, {phrase_years(term)}.",
        ])

    return convo(("system", SYSTEM), ("user", user), ("assistant", params_block(op, obj)))


# ============================================================================
# 4. Clarification: missing information -> ONE question, then the params.
#    Four-turn shape (user, assistant question, user reply, assistant
#    params), matched EXACTLY to build_dataset.py's make_clarification() --
#    see docs/STRATEGY_ASSISTANT_PIPELINE.md section 5, point 5, for why the
#    shape has to match whatever prompt builder assembles turns for serving.
#
#    Scoped to the five operations an ordinary homeowner phrases informally
#    enough to omit a field from -- the same curation call build_dataset.py
#    makes for its own three missing-field kinds (dte/symbol/asset_class)
#    rather than covering every field of every strategy.
# ============================================================================


def make_clarification(rng: random.Random) -> dict:
    scenario = rng.choice(["payment_term", "amortization_rate", "heloc_ltv",
                            "fvd_years", "rental_expenses"])

    if scenario == "payment_term":
        op = "ComputePayment"
        loan, annual_rate, term = sample_loan_scenario(rng)
        user = rng.choice([
            f"What's the payment on a {phrase_money(loan)} loan at {phrase_pct(annual_rate)}?",
            f"{phrase_money(loan)} at {phrase_pct(annual_rate)} -- what's the monthly payment?",
        ])
        ask = rng.choice(["Over how many years?", "What's the loan term?",
                          "How long is the loan -- 30, 15, or something else?"])
        term_word = rng.choice([str(term // 12), phrase_years(term)])
        follow = term_word
        obj = {"rate": rate_str(annual_rate / 12), "periods": term,
               "present_value": money_str(loan), "future_value": money_str(0),
               "timing": "END_OF_PERIOD"}

    elif scenario == "amortization_rate":
        op = "ComputeAmortization"
        loan, annual_rate, term = sample_loan_scenario(rng)
        user = rng.choice([
            f"Show me the amortization schedule for a {phrase_money(loan)} loan "
            f"over {phrase_years(term)}.",
            f"Amortize {phrase_money(loan)} over {phrase_years(term)}.",
        ])
        ask = rng.choice(["What's the interest rate?", "Which rate should I use?"])
        follow = phrase_pct(annual_rate)
        obj = {"loan_amount": money_str(loan), "annual_rate": rate_str(annual_rate, 4),
               "term_months": term, "monthly_overpayment": money_str(0),
               "pmi_annual_rate": rate_str(0, 4), "original_home_value": money_str(loan)}

    elif scenario == "heloc_ltv":
        op = "ComputeHeloc"
        home_value = round_money(rng.triangular(150_000, 1_800_000, 500_000))
        balance = round_money(home_value * rng.uniform(0.2, 0.75))
        drawn = round_money(rng.uniform(10_000, 100_000))
        annual_rate = round(rng.uniform(0.07, 0.11), 4)
        term_years = rng.choice([10, 15, 20])
        user = rng.choice([
            f"My home is worth {phrase_money(home_value)}, I owe {phrase_money(balance)}. "
            f"I want to draw {phrase_money(drawn)} from a HELOC at "
            f"{phrase_pct(annual_rate)} over {term_years} years.",
        ])
        ask = rng.choice(["What LTV cap should I use?", "What's the maximum loan-to-value?"])
        max_ltv = rng.choice([0.75, 0.80, 0.85, 0.90])
        follow = f"{int(max_ltv*100)}%"
        obj = {"home_value": money_str(home_value), "current_mortgage_balance": money_str(balance),
               "max_ltv_rate": rate_str(max_ltv, 2), "drawn_amount": money_str(drawn),
               "annual_rate": rate_str(annual_rate, 4), "repayment_term_years": term_years,
               "payments_per_year": 12}

    elif scenario == "fvd_years":
        op = "ComputeFutureValueDetailed"
        principal = round_money(rng.triangular(0, 300_000, 20_000))
        contribution = rng.choice([1200, 2400, 3600, 6000, 9000, 12000])
        annual_rate = round(rng.uniform(0.03, 0.09), 4)
        user = rng.choice([
            f"I have {phrase_money(principal)} saved and add "
            f"{phrase_money(contribution)} a year at {phrase_pct(annual_rate)}. "
            f"What will it grow to?",
        ])
        ask = rng.choice(["Over how many years?", "What's the time horizon?"])
        years = rng.randint(5, 40)
        follow = f"{years} years"
        obj = {"annual_rate": rate_str(annual_rate, 4), "years": years,
               "annual_contribution": money_str(contribution),
               "current_principal": money_str(principal),
               "annual_inflation_rate": rate_str(0, 4), "compound_frequency": 12}

    else:  # rental_expenses
        op = "ComputeRentalRoi"
        property_value = round_money(rng.triangular(80_000, 900_000, 250_000))
        cash_invested = round_money(property_value * rng.uniform(0.08, 0.30))
        gross_rent = round_money(rng.triangular(800, 6_000, 2_200))
        mortgage_payment = round_money(gross_rent * rng.uniform(0.4, 0.85))
        user = rng.choice([
            f"Rental worth {phrase_money(property_value)}, {phrase_money(cash_invested)} "
            f"cash invested, rent {phrase_money(gross_rent)}/month, mortgage payment "
            f"{phrase_money(mortgage_payment)}/month. What's my return?",
        ])
        ask = rng.choice(["What are the monthly operating expenses -- taxes, insurance, "
                          "maintenance?", "What do operating expenses run per month?"])
        opex = round_money(gross_rent * rng.uniform(0.2, 0.45))
        follow = phrase_money(opex)
        obj = {"property_value": money_str(property_value), "total_cash_invested": money_str(cash_invested),
               "periodic_gross_rent": money_str(gross_rent), "periodic_operating_expenses": money_str(opex),
               "periodic_mortgage_payment": money_str(mortgage_payment), "periods_per_year": 12}

    return convo(("system", SYSTEM), ("user", user), ("assistant", ask),
                 ("user", follow), ("assistant", params_block(op, obj)))


# ============================================================================
# 5. Modification: a follow-up that changes one field, keeping the rest.
#    Mirrors build_dataset.py's make_modification() shape exactly.
# ============================================================================


def make_modification(rng: random.Random) -> dict:
    kind = rng.choice(["amortization_rate", "amortization_overpay",
                       "amortization_term", "payment_loan_amount"])

    if kind == "payment_loan_amount":
        op = "ComputePayment"
        loan, annual_rate, term = sample_loan_scenario(rng)
        first = {"rate": rate_str(annual_rate / 12), "periods": term,
                 "present_value": money_str(loan), "future_value": money_str(0),
                 "timing": "END_OF_PERIOD"}
        new_loan = round_money(loan + rng.choice([-75_000, -50_000, -25_000, 25_000, 50_000, 75_000]))
        new_loan = max(new_loan, 50_000)
        second = dict(first)
        second["present_value"] = money_str(new_loan)
        first_user = (f"Payment on {phrase_money(loan)} at {phrase_pct(annual_rate)} "
                      f"over {phrase_years(term)}?")
        followup = rng.choice([f"what about {phrase_money(new_loan)} instead?",
                               f"redo it for {phrase_money(new_loan)}"])
    else:
        op = "ComputeAmortization"
        loan, annual_rate, term = sample_loan_scenario(rng)
        first = {"loan_amount": money_str(loan), "annual_rate": rate_str(annual_rate, 4),
                 "term_months": term, "monthly_overpayment": money_str(0),
                 "pmi_annual_rate": rate_str(0, 4), "original_home_value": money_str(loan)}
        first_user = (f"Amortize {phrase_money(loan)} at {phrase_pct(annual_rate)} over "
                      f"{phrase_years(term)}.")
        second = dict(first)
        if kind == "amortization_rate":
            new_rate = round(annual_rate + rng.choice([-0.01, -0.005, 0.005, 0.01, 0.015]), 4)
            new_rate = max(new_rate, 0.01)
            second["annual_rate"] = rate_str(new_rate, 4)
            followup = rng.choice([f"what if the rate is {phrase_pct(new_rate)} instead?",
                                   f"try {phrase_pct(new_rate)}"])
        elif kind == "amortization_overpay":
            overpay = rng.choice([100, 200, 300, 500, 750])
            second["monthly_overpayment"] = money_str(overpay)
            followup = rng.choice([f"now add {phrase_money(overpay)} extra a month",
                                   f"what if I pay {phrase_money(overpay)} more a month?"])
        else:  # amortization_term
            new_term = rng.choice([t for t in MORTGAGE_TERM_MONTHS if t != term])
            second["term_months"] = new_term
            followup = rng.choice([f"redo it over {phrase_years(new_term)}",
                                   f"what about a {phrase_years(new_term)} term?"])

    return convo(("system", SYSTEM), ("user", first_user),
                 ("assistant", params_block(op, first)),
                 ("user", followup), ("assistant", params_block(op, second)))


