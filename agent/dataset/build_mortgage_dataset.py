# -- ComputeAmortization / ComputeDetailedAmortization: full schedule.
def make_amortization_extraction(rng: random.Random) -> dict:
    # 50/50, not 70/30.
    #
    # These two operations differ by ONE trailing clause in the utterance and ONE
    # extra label field (annual_tax_rate); loan, rate, term, overpayment, PMI and
    # home value are identical. Under a 70/30 prior the cheapest thing a model can
    # do is ignore the clause and always answer the majority class -- which is
    # exactly what v7 did: 24 of 24 ComputeDetailedAmortization failures named
    # ComputeAmortization instead, taking that operation from 33/34 to 10/34.
    # A thin signal cannot outvote a strong prior, so the prior goes.
    op = rng.choices(["ComputeAmortization", "ComputeDetailedAmortization"],
                      [0.5, 0.5])[0]
    loan, annual_rate, term = sample_loan_scenario(rng)
    overpay = rng.choices([0, 50, 100, 150, 200, 300, 500, 750, 1000],
                           [0.55, 0.06, 0.06, 0.06, 0.06, 0.06, 0.06, 0.05, 0.04])[0]
    tax_rate = round(rng.uniform(0.15, 0.37), 4)

    # Whether PMI is mentioned is decided BEFORE home_value/PMI are sampled,
    # not after -- the reverse order is exactly the bug documented on
    # `future_value` above and in build_dataset.py's own make_extraction
    # comment. When not mentioned, home_value defaults to loan_amount (no
    # PMI, the same "not stated -> base case" convention used everywhere
    # else in this file for monthly_overpayment/payments_per_year/timing).
    mention_pmi = rng.random() < 0.35
    if mention_pmi:
        ltv = rng.uniform(0.8001, 0.97)
        home_value = round_money(loan / ltv)
        pmi = round(rng.uniform(0.003, 0.012), 4)
    else:
        home_value = loan
        pmi = 0.0

    base = (f"Amortization schedule for a {phrase_money(loan)} loan at "
            f"{phrase_pct(annual_rate)} over {phrase_years(term)}")
    if overpay:
        base += f", paying an extra {phrase_money(overpay)}/month"
    if mention_pmi:
        base += (f". Home is worth {phrase_money(home_value)}, PMI runs "
                 f"{phrase_pct(pmi)} a year")
    base += "."
    if op == "ComputeDetailedAmortization":
        # Vary the cue and let it lead sometimes. A single fixed clause always in
        # final position is the weakest possible signal for the one thing that
        # separates these two operations.
        base += rng.choice([
            f" I'm in the {phrase_pct(tax_rate)} tax bracket -- show the "
            f"interest deduction too.",
            f" Include the mortgage interest tax deduction at my "
            f"{phrase_pct(tax_rate)} marginal rate.",
            f" I need the after-tax numbers as well; my marginal rate is "
            f"{phrase_pct(tax_rate)}.",
            f" Break out the deductible interest -- {phrase_pct(tax_rate)} "
            f"bracket.",
        ])

    compact = (f"Show me the full payment schedule on {phrase_money(loan)}, "
               f"{phrase_pct(annual_rate)}, {phrase_years(term)}"
               + (f", {phrase_money(overpay)} extra a month" if overpay else "")
               + (f". Home is worth {phrase_money(home_value)}, PMI {phrase_pct(pmi)}/yr"
                  if mention_pmi else "")
               + (f", tax rate {phrase_pct(tax_rate)}" if op == "ComputeDetailedAmortization" else "")
               + ".")
    if op == "ComputeDetailedAmortization":
        # Lead with the deduction in the compact template too, so the cue is not
        # always the last thing before the full stop.
        compact = (f"With the interest deduction at {phrase_pct(tax_rate)}: " + compact)
    user = rng.choice([base, compact])

    obj = {"loan_amount": money_str(loan), "annual_rate": rate_str(annual_rate, 4),
           "term_months": term, "monthly_overpayment": money_str(overpay),
           "pmi_annual_rate": rate_str(pmi, 4), "original_home_value": money_str(home_value)}
    if op == "ComputeDetailedAmortization":
        obj["annual_tax_rate"] = rate_str(tax_rate, 4)
    return convo(("system", SYSTEM), ("user", user),
                 ("assistant", params_block(op, obj)))


# -- ComputeAmortizationBatch: several loan offers compared side by side.
# Fields here are `double`/`int32`, NOT the BigDecimal `string` the other
# mortgage RPCs use (see finance.proto's own numeric-types note at the top of
# the file) -- caught only because the field types are parsed, not assumed.
def make_amortization_batch_extraction(rng: random.Random) -> dict:
    op = "ComputeAmortizationBatch"
    n = rng.choice([2, 2, 3])
    scenarios = []
    for _ in range(n):
        loan, annual_rate, term = sample_loan_scenario(rng)
        overpay = rng.choice([0, 0, 100, 200, 300])
        # No template below states a home value or PMI rate for any scenario
        # in the comparison, so both stay at the "not stated" default (no
        # PMI, home_value == loan_amount) -- see make_amortization_extraction
        # for why sampling these independent of whether the text mentions
        # them is a defect, not a source of harmless variety.
        pmi = 0.0
        home_value = loan
        scenarios.append((loan, annual_rate, term, overpay, pmi, home_value))

    descs = [f"{phrase_money(l)} at {phrase_pct(r)} over {phrase_years(t)}"
             + (f" with {phrase_money(o)}/month extra" if o else "")
             for (l, r, t, o, _, _) in scenarios]
    user = rng.choice([
        "Compare these loan offers: " + "; ".join(descs) + ".",
        "Which of these is cheapest -- " + ", or ".join(descs) + "?",
    ])
    obj = {
        "loan_amounts": [round(l, 2) for l, *_ in scenarios],
        "annual_rates": [round(r, 4) for _, r, *_ in scenarios],
        "term_months": [t for _, _, t, *_ in scenarios],
        "extra_payments": [round(o, 2) for _, _, _, o, _, _ in scenarios],
        "pmi_rates": [round(p, 4) for *_, p, _ in scenarios],
        "home_values": [round(h, 2) for *_, h in scenarios],
    }
    return convo(("system", SYSTEM), ("user", user),
                 ("assistant", params_block(op, obj)))


# -- ComputeHeloc.
def make_heloc_extraction(rng: random.Random) -> dict:
    op = "ComputeHeloc"
    home_value = round_money(rng.triangular(150_000, 1_800_000, 500_000))
    balance = round_money(home_value * rng.uniform(0.2, 0.75))
    max_ltv = rng.choice([0.75, 0.80, 0.85, 0.90])
    available = max(home_value * max_ltv - balance, 10_000)
    drawn = round_money(min(available, rng.uniform(10_000, available)))
    annual_rate = round(rng.uniform(0.07, 0.11), 4)
    term_years = rng.choice([10, 15, 20])
    # No template below states a payment frequency, so it stays at the
    # standard monthly default rather than an unstated 15% chance of
    # biweekly -- same "don't sample what the text can't say" rule as
    # everywhere else in this file.
    payments_per_year = 12

    user = rng.choice([
        f"My house is worth {phrase_money(home_value)} and I owe "
        f"{phrase_money(balance)} on it. If I draw {phrase_money(drawn)} from a "
        f"HELOC at {phrase_pct(annual_rate)} with an {int(max_ltv*100)}% LTV cap, "
        f"repaid over {term_years} years, what are the payments?",
        f"Home value {phrase_money(home_value)}, mortgage balance "
        f"{phrase_money(balance)}, {int(max_ltv*100)}% LTV limit. HELOC draw of "
        f"{phrase_money(drawn)} at {phrase_pct(annual_rate)}, {term_years}-year "
        f"repayment.",
        f"How much equity can I borrow against a {phrase_money(home_value)} home "
        f"with a {phrase_money(balance)} mortgage balance, {int(max_ltv*100)}% LTV "
        f"cap? I'd draw {phrase_money(drawn)} at {phrase_pct(annual_rate)} over "
        f"{term_years} years.",
    ])
    obj = {"home_value": money_str(home_value), "current_mortgage_balance": money_str(balance),
           "max_ltv_rate": rate_str(max_ltv, 2), "drawn_amount": money_str(drawn),
           "annual_rate": rate_str(annual_rate, 4), "repayment_term_years": term_years,
           "payments_per_year": payments_per_year}
    return convo(("system", SYSTEM), ("user", user),
                 ("assistant", params_block(op, obj)))


# -- ComputeNpv / ComputeIrr / ComputeXnpv / ComputeXirr: a cash-flow series.
# Xnpv/Xirr add irregular dates; Npv/Irr assume a regular annual grid. Which
# op fires follows directly from what the sentence supplies: a stated
# discount rate -> NPV-family (XNPV if dates are irregular); no rate, asking
# "what return" -> IRR-family.
def make_cashflow_extraction(rng: random.Random) -> dict:
    dated = rng.random() < 0.35
    op = rng.choice((["ComputeXnpv", "ComputeXirr"] if dated
                      else ["ComputeNpv", "ComputeIrr"]))
    outlay = round_money(rng.triangular(5_000, 500_000, 60_000))
    n = rng.randint(3, 6)
    flows = [round(rng.triangular(2_000, 150_000, 20_000), 2) for _ in range(n)]
    values = [-outlay] + flows
    discount_rate = round(rng.uniform(0.04, 0.12), 4)

    if dated:
        days = [0]
        for _ in range(n):
            days.append(days[-1] + round(rng.triangular(300, 430, 365)))
        flow_desc = "; ".join(
            f"{phrase_money(f)} after {d} days" for f, d in zip(flows, days[1:]))
    else:
        flow_desc = "; ".join(f"year {i+1}: {phrase_money(f)}" for i, f in enumerate(flows))

    if op in ("ComputeNpv", "ComputeXnpv"):
        user = (f"I invest {phrase_money(outlay)} today and expect back {flow_desc}. "
                f"What's the NPV at a {phrase_pct(discount_rate)} discount rate?")
    else:
        user = (f"I invest {phrase_money(outlay)} today and expect back {flow_desc}. "
                f"What return (IRR) am I getting?")

    obj = {}
    if "rate" in op_field_names(op):
        obj["rate"] = round(discount_rate, 6)
    obj["values"] = values
    if "dates" in op_field_names(op):
        obj["dates"] = [float(d) for d in days]
    if "guess" in op_field_names(op):
        obj["guess"] = 0.1
    return convo(("system", SYSTEM), ("user", user),
                 ("assistant", params_block(op, obj)))


# -- ComputePaybackPeriod: generic investment payback. Deliberately phrased
# as a general investment ("solar panels", "new equipment"), never as
# "refinance break-even" -- that phrase is reserved for the speculative
# refinance_break_even future op (see FUTURE_OPS) so the two are never
# conflated in what the model is taught to call.
def make_payback_extraction(rng: random.Random) -> dict:
    op = "ComputePaybackPeriod"
    outlay = round_money(rng.triangular(2_000, 80_000, 15_000))
    annual_saving = round_money(rng.triangular(500, 12_000, 2_500))
    discounted = rng.random() < 0.35
    rate = round(rng.uniform(0.03, 0.08), 4) if discounted else 0.0
    thing = rng.choice(["solar panels", "a heat pump", "new windows",
                         "an energy retrofit", "equipment for my rental"])

    # GROUND THE OUTLAY'S ROLE, in half the rows.
    #
    # `values[0]` is the outlay as a NEGATIVE number, and the minus sign is a
    # cash-flow convention the utterance never states. Both corpora taught it
    # perfectly consistently -- 344/344 and 328/328 rows -- and a model trained
    # on the second one still dropped it on 14 of 20 held-out rows, emitting
    # `[14900, 4800, ...]` for `[-14900, 4800, ...]`.
    #
    # It is not forgetting and it is not rank. Commit 96decdb deliberately
    # taught the model to stop answering from a prior and start reading the
    # utterance; the fields that lost are exactly those whose gold is NOT
    # derivable from the utterance, and this is one of them. The measured
    # signature is the same shift elsewhere in the corpus: `new_pmi_monthly`
    # came back as the stated monthly payment, `pmi_drop_off_ltv` as 0.30
    # scraped from "30 years". The model is doing what it was retrained to do.
    #
    # So the fix is to make the sign READABLE rather than to demand it be
    # remembered -- the same move that took closing costs 15/42 to 39/42. Half
    # the rows keep the original phrasing so the convention still has to
    # survive an utterance that does not mark it.
    spend = rng.choice([
        f"I'm putting {phrase_money(outlay)} into {thing}",
        f"{phrase_money(outlay)} out of pocket for {thing}",
        f"I'm spending {phrase_money(outlay)} up front on {thing}",
        f"An upfront cost of {phrase_money(outlay)} for {thing}",
    ]) if rng.random() < 0.5 else f"I'm putting {phrase_money(outlay)} into {thing}"
    user = (f"{spend} that saves me about "
            f"{phrase_money(annual_saving)} a year." +
            (f" Using a {phrase_pct(rate)} discount rate, " if discounted else " ") +
            "how many years until it pays for itself?")
    values = [-outlay] + [annual_saving] * 20
    obj = {"values": values, "discounted": discounted, "rate": rate}
    return convo(("system", SYSTEM), ("user", user),
                 ("assistant", params_block(op, obj)))


